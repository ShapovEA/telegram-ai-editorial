def writer(mode: str, fmt: str) -> str:
    fact_blocks = (
        "ФАКТЫ ОТ РАССЛЕДОВАТЕЛЯ, ВЫЧИСЛЕНИЯ, ИНФОПОВОД и ТЕКСТ ИСТОЧНИКА"
        if mode == "news"
        else "ФАКТЫ ОТ РАССЛЕДОВАТЕЛЯ, ВЫЧИСЛЕНИЯ и ЗАДАНИЕ"
    )
    lines = [line.replace("{fact_blocks}", fact_blocks) for line in _WRITER_COMMON]
    return _block(_WRITER_FORMAT.get(fmt, _WRITER_FORMAT["text"]), *_WRITER_MODE[mode], *lines)


